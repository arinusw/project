/*=============== CONTACT FORM AJAX ===============*/
const contactForm = document.getElementById('contact-form'),
      contactMessage = document.getElementById('contact-message')

const sendEmail = (e) => {
    e.preventDefault()

    // Show loading message
    contactMessage.textContent = 'Mengirim pesan... ⏳'
    contactMessage.style.color = 'var(--title-color)'

    const formData = new FormData(contactForm)

    fetch('contact.php', {
        method: 'POST',
        body: formData
    })
    .then(response => response.json())
    .then(data => {
        if (data.status === 'success') {
            contactMessage.textContent = 'Pesan berhasil dikirim! ✅'
            contactMessage.style.color = 'green'
            contactForm.reset()
        } else {
            contactMessage.textContent = 'Ups! Terjadi kesalahan. Silakan coba lagi. ❌'
            contactMessage.style.color = 'red'
        }
    })
    .catch(error => {
        contactMessage.textContent = 'Ups! Terjadi kesalahan koneksi. ❌'
        contactMessage.style.color = 'red'
    })
    .finally(() => {
        setTimeout(() => {
            contactMessage.textContent = ''
        }, 5000)
    })
}

if (contactForm) {
    contactForm.addEventListener('submit', sendEmail)
}
